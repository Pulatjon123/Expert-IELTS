import { z } from "zod";
import { prisma } from "@/lib/db";
import { requireUser } from "@/lib/auth";
import { handler, json } from "@/lib/api";
import { generateWritingQuestion } from "@/lib/ai/writing";
import { TASK2_CATEGORIES } from "@/lib/ielts";

const Body = z.discriminatedUnion("task", [
  // Generated Task 1 questions are limited to chart/table types the app can render from data.
  z.object({ task: z.literal("TASK1"), category: z.enum(["LINE_GRAPH", "BAR_CHART", "PIE_CHART", "TABLE"]) }),
  z.object({ task: z.literal("TASK2"), category: z.enum(TASK2_CATEGORIES) }),
]);

const CHART_TYPE = { LINE_GRAPH: "line", BAR_CHART: "bar", PIE_CHART: "pie", TABLE: "table" } as const;

/** Creates a new AI-generated practice question. It is permanently labelled AI_GENERATED and reused by other students. */
export const POST = handler(async (req: Request) => {
  const user = await requireUser();
  const body = Body.parse(await req.json());
  const topics = (await prisma.writingQuestion.findMany({ where: { task: body.task }, select: { topic: true }, distinct: ["topic"] })).map((t) => t.topic);
  const { data } = await generateWritingQuestion(body.task, body.category, topics, user.id);
  let visual: object | undefined;
  if (body.task === "TASK1") {
    const c = data.chart;
    const type = CHART_TYPE[body.category];
    visual =
      type === "table"
        ? { type, title: c.title, columns: c.columns, rows: c.rows }
        : { type, title: c.title, unit: c.unit, categories: c.categories, series: c.series };
  }
  const q = await prisma.writingQuestion.create({
    data: {
      task: body.task,
      category: body.category,
      topic: data.topic.slice(0, 80),
      prompt: data.prompt,
      visual,
      source: "AI_GENERATED",
      sourceNote: "Generated by AI for practice. Not a real exam question.",
    },
  });
  await prisma.questionHistory.create({ data: { userId: user.id, skill: "WRITING", questionId: q.id } });
  return json({ questionId: q.id });
});
