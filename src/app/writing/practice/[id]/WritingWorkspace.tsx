"use client";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { useCallback, useEffect, useRef, useState } from "react";
import { Bookmark, BookmarkCheck, Clock, History, RefreshCw, Save, Send, Lightbulb, PenLine, Layers } from "lucide-react";
import { Alert, BandPill, Button, Card, cn, Spinner } from "@/components/ui";
import { Task1Visual, type Visual } from "@/components/Task1Visual";
import { CategoryBadge, SourceBadge } from "@/components/QuestionMeta";
import { api, ApiError } from "@/lib/fetcher";
import { countWords, MIN_WORDS, TIME_LIMIT_MIN } from "@/lib/ielts";
import { useI18n } from "@/lib/i18n/client";
import type { Locale } from "@/lib/i18n/dict";
import type { WritingPrep } from "@/lib/ai/writing";
import { PrepView } from "./PrepView";

export interface QuestionData {
  id: string;
  task: "TASK1" | "TASK2";
  category: string;
  topic: string;
  prompt: string;
  visual: Visual | null;
  imageUrl: string | null;
  source: "VERIFIED_REPORT" | "AI_GENERATED" | "PRACTICE";
  sourceNote: string | null;
  reportedAt: string | null;
}

interface Attempt {
  id: string;
  content: string;
  timeSpentSec: number;
  status: string;
}

export function WritingWorkspace({
  locale,
  question,
  initialBookmarked,
  initialPrep,
  aiConfigured,
  previous,
  focus,
}: {
  focus?: React.ReactNode;
  locale: Locale;
  question: QuestionData;
  initialBookmarked: boolean;
  initialPrep: WritingPrep | null;
  aiConfigured: boolean;
  previous: { id: string; date: string; band: number | null }[];
}) {
  const { t } = useI18n();
  const router = useRouter();
  const [tab, setTab] = useState<"prep" | "write">("prep");
  const [bookmarked, setBookmarked] = useState(initialBookmarked);
  const [nextLoading, setNextLoading] = useState(false);

  async function another() {
    setNextLoading(true);
    try {
      const { questionId } = await api<{ questionId: string }>(`/api/writing/next?task=${question.task}&category=${question.category}&exclude=${question.id}`);
      router.push(`/writing/practice/${questionId}`);
    } catch {
      const { questionId } = await api<{ questionId: string }>(`/api/writing/next?task=${question.task}&exclude=${question.id}`);
      router.push(`/writing/practice/${questionId}`);
    }
  }

  return (
    <div className="mx-auto max-w-6xl px-4 py-8 sm:px-6">
      <Link href="/writing" className="text-sm text-muted hover:text-text">← {t("writing.title")}</Link>

      <Card className="mt-3 p-5 sm:p-6">
        <div className="flex flex-wrap items-center gap-2">
          <span className="text-sm font-semibold">{question.task === "TASK1" ? t("writing.task1") : t("writing.task2")}</span>
          <CategoryBadge category={question.category} locale={locale} />
          <SourceBadge source={question.source} note={question.sourceNote} reportedAt={question.reportedAt} locale={locale} />
          <span className="text-xs text-muted">{question.topic}</span>
          <div className="ml-auto flex gap-1">
            <Button
              variant="ghost"
              size="sm"
              onClick={async () => {
                const r = await api<{ bookmarked: boolean }>("/api/bookmarks", { method: "POST", json: { skill: "WRITING", questionId: question.id } });
                setBookmarked(r.bookmarked);
              }}
              aria-label="Bookmark"
            >
              {bookmarked ? <BookmarkCheck className="h-4 w-4 text-accent" /> : <Bookmark className="h-4 w-4" />}
            </Button>
            <Button variant="ghost" size="sm" onClick={another} loading={nextLoading}>
              <RefreshCw className="h-4 w-4" /> {t("writing.newQuestion")}
            </Button>
          </div>
        </div>
        <p className="mt-4 whitespace-pre-line leading-relaxed">{question.prompt}</p>
        {question.visual && (
          <div className="mt-4">
            <Task1Visual visual={question.visual} />
          </div>
        )}
        {question.imageUrl && (
          // eslint-disable-next-line @next/next/no-img-element
          <img src={question.imageUrl} alt="Task 1 diagram" className="mt-4 max-h-[480px] rounded-xl border border-border" />
        )}
        {question.source === "AI_GENERATED" && <p className="mt-3 text-xs text-muted">This question was generated by AI for practice. It is not claimed to be a real IELTS exam question.</p>}
        {previous.length > 0 && (
          <div className="mt-4 flex flex-wrap items-center gap-2 text-sm text-muted">
            Previous attempts:
            {previous.map((p) => (
              <Link key={p.id} href={`/writing/attempts/${p.id}`} className="hover:opacity-80">
                <BandPill band={p.band} />
              </Link>
            ))}
          </div>
        )}
      </Card>

      {focus && <div className="mt-4">{focus}</div>}

      <div className="mt-6 flex gap-1 rounded-xl bg-surface-2 p-1 sm:w-fit" role="tablist">
        {(
          [
            ["prep", t("writing.prepare"), Lightbulb],
            ["write", t("writing.write"), PenLine],
          ] as const
        ).map(([k, label, Icon]) => (
          <button
            key={k}
            role="tab"
            aria-selected={tab === k}
            onClick={() => setTab(k)}
            className={cn("flex flex-1 items-center justify-center gap-2 rounded-lg px-4 py-2 text-sm font-medium sm:flex-none", tab === k ? "bg-surface shadow-sm" : "text-muted hover:text-text")}
          >
            <Icon className="h-4 w-4" /> {label}
          </button>
        ))}
        <Link
          href={`/writing/compare/${question.id}`}
          className="flex flex-1 items-center justify-center gap-2 rounded-lg px-4 py-2 text-sm font-medium text-muted hover:text-text sm:flex-none"
        >
          <Layers className="h-4 w-4" /> Band 6 / 7 / 8
        </Link>
      </div>

      <div className="mt-4">
        <div hidden={tab !== "prep"}>
          <PrepView questionId={question.id} topic={question.topic} initial={initialPrep} aiConfigured={aiConfigured} onStartWriting={() => setTab("write")} />
        </div>
        <div hidden={tab !== "write"}>
          <Editor question={question} active={tab === "write"} aiConfigured={aiConfigured} />
        </div>
      </div>
    </div>
  );
}

function formatTime(sec: number) {
  const s = Math.abs(sec);
  return `${sec < 0 ? "+" : ""}${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;
}

function Editor({ question, active, aiConfigured }: { question: QuestionData; active: boolean; aiConfigured: boolean }) {
  const { t } = useI18n();
  const router = useRouter();
  const [attempt, setAttempt] = useState<Attempt | null>(null);
  const [text, setText] = useState("");
  const [elapsed, setElapsed] = useState(0);
  const [running, setRunning] = useState(false);
  const [saveState, setSaveState] = useState<"idle" | "saving" | "saved" | "error">("idle");
  const [error, setError] = useState<{ msg: string; code?: string } | null>(null);
  const [submitting, setSubmitting] = useState(false);
  const [showHistory, setShowHistory] = useState(false);
  const [versions, setVersions] = useState<{ id: string; content: string; wordCount: number; createdAt: string }[] | null>(null);
  const dirty = useRef(false);
  const latest = useRef({ text: "", elapsed: 0 });
  latest.current = { text, elapsed };

  const limit = TIME_LIMIT_MIN[question.task] * 60;
  const min = MIN_WORDS[question.task];
  const words = countWords(text);

  // Load or create the draft attempt.
  useEffect(() => {
    let cancelled = false;
    api<{ attempt: Attempt }>("/api/writing/attempts", { method: "POST", json: { questionId: question.id } })
      .then(({ attempt }) => {
        if (cancelled) return;
        let content = attempt.content;
        try {
          const backup = localStorage.getItem(`ei_draft_${attempt.id}`);
          if (backup && backup.length > content.length) content = backup;
        } catch {}
        setAttempt(attempt);
        setText(content);
        setElapsed(attempt.timeSpentSec);
      })
      .catch((e) => setError({ msg: (e as Error).message }));
    return () => {
      cancelled = true;
    };
  }, [question.id]);

  // Timer runs while the editor tab is open and the student has started typing.
  useEffect(() => {
    if (!active || !running) return;
    const iv = setInterval(() => setElapsed((e) => e + 1), 1000);
    return () => clearInterval(iv);
  }, [active, running]);

  const save = useCallback(
    async (snapshot = false) => {
      if (!attempt) return;
      setSaveState("saving");
      try {
        await api(`/api/writing/attempts/${attempt.id}`, { method: "PATCH", json: { content: latest.current.text, timeSpentSec: latest.current.elapsed, snapshot } });
        dirty.current = false;
        setSaveState("saved");
        try {
          localStorage.removeItem(`ei_draft_${attempt.id}`);
        } catch {}
      } catch (e) {
        setSaveState("error");
        setError({ msg: (e as Error).message });
      }
    },
    [attempt],
  );

  // Auto-save 1.5 s after the student stops typing, and every 30 s while the timer runs.
  useEffect(() => {
    if (!attempt || !dirty.current) return;
    const tm = setTimeout(() => save(false), 1500);
    return () => clearTimeout(tm);
  }, [text, attempt, save]);
  useEffect(() => {
    if (!running) return;
    const iv = setInterval(() => save(false), 30000);
    return () => clearInterval(iv);
  }, [running, save]);

  async function submit() {
    if (!attempt) return;
    if (words < min && !confirm(`Your answer has ${words} words — below the ${min}-word minimum, which lowers the Task score. Submit anyway?`)) return;
    setSubmitting(true);
    setError(null);
    try {
      await save(false);
      await api(`/api/writing/attempts/${attempt.id}/submit`, { method: "POST" });
      router.push(`/writing/attempts/${attempt.id}`);
    } catch (e) {
      setError({ msg: (e as Error).message, code: e instanceof ApiError ? e.code : undefined });
      setSubmitting(false);
    }
  }

  async function openHistory() {
    setShowHistory((s) => !s);
    if (attempt && !versions) {
      const r = await api<{ versions: { id: string; content: string; wordCount: number; createdAt: string }[] }>(`/api/writing/attempts/${attempt.id}/versions`);
      setVersions(r.versions);
    }
  }

  if (!attempt) return error ? <Alert tone="danger">{error.msg}</Alert> : <Spinner />;

  const remaining = limit - elapsed;
  return (
    <div className="grid gap-4 lg:grid-cols-[1fr_260px]">
      <Card className="flex flex-col p-0">
        <div className="flex flex-wrap items-center gap-3 border-b border-border px-4 py-2.5 text-sm">
          <span className={cn("font-semibold tabular-nums", words >= min ? "text-success" : "text-text")}>
            {words} {t("writing.words")}
          </span>
          <span className="text-muted">/ {min}+</span>
          <span className="ml-auto text-xs text-muted">
            {saveState === "saving" ? "Saving…" : saveState === "saved" ? t("writing.autosaved") : saveState === "error" ? "Not saved" : ""}
          </span>
        </div>
        <textarea
          value={text}
          onChange={(e) => {
            setText(e.target.value);
            dirty.current = true;
            if (!running) setRunning(true);
            try {
              localStorage.setItem(`ei_draft_${attempt.id}`, e.target.value);
            } catch {}
          }}
          spellCheck={false}
          autoCorrect="off"
          autoCapitalize="off"
          placeholder="Write your answer here. Spell-check is off, as in the real test."
          className="min-h-[480px] w-full flex-1 resize-y bg-transparent px-5 py-4 font-serif text-[17px] leading-8 outline-none"
          aria-label="Essay editor"
        />
      </Card>

      <div className="space-y-4">
        <Card className="p-4">
          <div className="flex items-center gap-2 text-sm text-muted">
            <Clock className="h-4 w-4" /> {t("writing.timer")} · {TIME_LIMIT_MIN[question.task]} min
          </div>
          <p className={cn("mt-1 text-3xl font-semibold tabular-nums", remaining < 0 ? "text-danger" : remaining < 300 ? "text-warning" : "")}>{formatTime(remaining)}</p>
          {remaining < 0 && <p className="text-xs text-danger">Over time — in the exam you would have to stop.</p>}
          <Button variant="secondary" size="sm" className="mt-3 w-full" onClick={() => setRunning((r) => !r)}>
            {running ? "Pause timer" : elapsed ? "Resume timer" : "Start timer"}
          </Button>
        </Card>
        <Card className="space-y-2 p-4">
          <Button variant="secondary" className="w-full" onClick={() => save(true)}>
            <Save className="h-4 w-4" /> {t("writing.saveDraft")}
          </Button>
          <Button variant="ghost" className="w-full" onClick={openHistory}>
            <History className="h-4 w-4" /> {t("writing.history")}
          </Button>
          <Button className="w-full" size="lg" onClick={submit} loading={submitting} disabled={words < 30 || !aiConfigured}>
            <Send className="h-4 w-4" /> {t("writing.submit")}
          </Button>
          {!aiConfigured && <p className="text-xs text-warning">{t("common.notConfigured")}</p>}
          {submitting && <p className="text-xs text-muted">The examiner is reading your answer. This usually takes 30–90 seconds.</p>}
        </Card>
        {error && <Alert tone={error.code === "AI_NOT_CONFIGURED" || error.code === "AI_LIMIT" ? "warning" : "danger"}>{error.msg}</Alert>}
        {showHistory && (
          <Card className="max-h-80 overflow-y-auto p-4">
            <p className="text-sm font-semibold">{t("writing.history")}</p>
            {!versions ? (
              <Spinner className="mt-2 h-4 w-4" />
            ) : versions.length ? (
              <ul className="mt-2 space-y-2 text-sm">
                {versions.map((v) => (
                  <li key={v.id} className="flex items-center justify-between gap-2">
                    <span className="text-muted">
                      {new Date(v.createdAt).toLocaleString(undefined, { dateStyle: "short", timeStyle: "short" })} · {v.wordCount} w
                    </span>
                    <button
                      className="text-xs font-medium text-primary hover:underline"
                      onClick={() => {
                        if (confirm("Replace the current text with this saved version?")) {
                          setText(v.content);
                          dirty.current = true;
                        }
                      }}
                    >
                      Restore
                    </button>
                  </li>
                ))}
              </ul>
            ) : (
              <p className="mt-2 text-sm text-muted">No saved versions yet. Click “{t("writing.saveDraft")}” to keep one.</p>
            )}
          </Card>
        )}
      </div>
    </div>
  );
}
