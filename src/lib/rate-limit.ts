import "server-only";

// Simple in-memory fixed-window limiter (per server instance). Good enough for login brute-force protection
// on a single instance; use Redis/Upstash when running multiple instances.
const buckets = new Map<string, { count: number; reset: number }>();

export function rateLimit(key: string, limit: number, windowMs: number): boolean {
  const now = Date.now();
  const b = buckets.get(key);
  if (!b || b.reset < now) {
    buckets.set(key, { count: 1, reset: now + windowMs });
    return true;
  }
  b.count += 1;
  return b.count <= limit;
}
